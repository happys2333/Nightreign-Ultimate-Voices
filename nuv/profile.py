"""Clone an offline ME3 profile without editing the user's existing profile."""
from copy import deepcopy
from pathlib import Path
import tomllib
import tomli_w

PACKAGE_ID = "nightreign-ultimate-voices"


def _read(source: Path) -> dict:
    data = tomllib.loads(Path(source).read_text(encoding="utf-8-sig"))
    for key in ("includes", "include", "profile"):
        if key in data:
            raise ValueError(f"Profile {key} inheritance is unsupported; use a self-contained ME3 profile")
    return data


def _resolved(source: Path, name: str) -> Path:
    path = Path(name).expanduser()
    return (path if path.is_absolute() else source.parent / path).resolve()


def effective_packages(source: Path) -> list[Path]:
    source = Path(source).resolve()
    packages = _read(source).get("packages", [])
    by_id = {}
    for package in packages:
        identifier = package.get("id")
        if not identifier or identifier in by_id:
            raise ValueError("Every ME3 package needs a unique id")
        if "path" not in package:
            raise ValueError(f"ME3 package {identifier} needs an explicit local path")
        by_id[identifier] = package
    dependencies = {identifier: set() for identifier in by_id}
    for identifier, package in by_id.items():
        for dependency in package.get("load_after", []):
            target = dependency["id"]
            if target in by_id:
                dependencies[identifier].add(target)
            elif not dependency.get("optional", False):
                raise ValueError(f"Missing ME3 package dependency: {target}")
        for dependency in package.get("load_before", []):
            target = dependency["id"]
            if target in by_id:
                dependencies[target].add(identifier)
            elif not dependency.get("optional", False):
                raise ValueError(f"Missing ME3 package dependency: {target}")
    ordered = []
    while dependencies:
        ready = next((key for key, values in dependencies.items() if not values), None)
        if ready is None:
            raise ValueError("ME3 package dependency cycle")
        ordered.append(_resolved(source, by_id[ready]["path"]))
        dependencies.pop(ready)
        for values in dependencies.values():
            values.discard(ready)
    return ordered


def create_profile(source: Path | None, mod_directory: Path) -> str:
    if source is None:
        data = {"profileVersion": "v1", "start_online": False, "supports": [{"game": "nightreign"}]}
    else:
        source = Path(source).resolve()
        data = deepcopy(_read(source))
        if data.get("start_online", False) is not False:
            raise ValueError("Choose an offline/seamless profile (start_online=false)")
        supports = data.get("supports", [])
        if not supports or any(item.get("game") != "nightreign" for item in supports):
            raise ValueError("Choose a Nightreign ME3 profile")
        effective_packages(source)
        for kind in ("packages", "natives"):
            for item in data.get(kind, []):
                if "path" not in item:
                    raise ValueError(f"ME3 {kind} entry needs an explicit local path")
                item["path"] = _resolved(source, item["path"]).as_posix()
    data["start_online"] = False
    packages = data.setdefault("packages", [])
    if any(package.get("id") == PACKAGE_ID for package in packages):
        raise ValueError("This profile already contains Ultimate Voices; select the original profile")
    dependencies = [{"id": item["id"], "optional": False} for item in packages]
    packages.append({"id": PACKAGE_ID, "path": Path(mod_directory).resolve().as_posix(), "load_after": dependencies})
    return "# Generated by Nightreign Ultimate Voices; original profile unchanged.\n" + tomli_w.dumps(data)
